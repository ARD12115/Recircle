"""
Reports Endpoint - POST /reports
"""
from fastapi import APIRouter, Depends
from fastapi.responses import StreamingResponse
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy import select
import io

from app.core.security import get_manager_user
from app.db.session import get_db
from app.models.scan import Scan
from app.models.user import User
from app.services.twin.metrics import compute_current_metrics
from app.services.advisor.advisor import generate_advice

router = APIRouter()


@router.post("")
async def generate_report(
    db: AsyncSession = Depends(get_db),
    user: dict = Depends(get_manager_user),
):
    """Generate sustainability report as markdown (print-to-PDF on frontend)."""
    user_id = int(user["sub"]) if not user.get("demo") else None
    
    # Get metrics
    metrics = await compute_current_metrics(db)
    
    # Get advice
    advice = await generate_advice(db, user_id, use_cached=True)
    
    # Get user scans
    scans = []
    if user_id:
        result = await db.execute(select(Scan).where(Scan.user_id == user_id).order_by(Scan.created_at.desc()).limit(50))
        scans = result.scalars().all()
    
    # Build markdown report
    md = f"""# ReCircle Sustainability Report

**Generated:** {metrics.timestamp.strftime('%Y-%m-%d %H:%M UTC')}
**User:** {user.get('email', 'Manager')}
**Period:** Last 30 days

---

## Executive Summary

{advice.summary}

---

## Key Metrics

| Metric | Value |
|--------|-------|
| Diversion Rate | {metrics.diversion_rate:.1%} |
| Contamination Rate | {metrics.contamination_rate:.1%} |
| CO2e Avoided | {metrics.co2e_avoided_kg:.1f} kg |
| Pickup Cost | ${metrics.pickup_cost:.0f} |
| Total Items Tracked | {metrics.total_items} |
| Items Recovered | {metrics.recovered_items} |

---

## Issues Identified

"""
    
    for issue in advice.issues:
        md += f"- {issue}\n"
    
    md += "\n## Recommended Actions\n\n"
    
    for i, action in enumerate(advice.actions, 1):
        md += f"""### {i}. {action.title}

**Why:** {action.why}

**Expected Impact:** {action.expected_impact}

**Effort:** {action.effort.title()}

**Owner:** {action.owner.title()}

"""
    
    md += "## Reuse & Upcycling Ideas\n\n"
    for idea in advice.reuse_ideas:
        md += f"- {idea}\n"
    
    md += f"""

---

## Personal Scan History ({len(scans)} scans)

| Date | Item | Class | Confidence | Bin |
|------|------|-------|------------|-----|
"""
    
    for scan in scans[:20]:
        md += f"| {scan.created_at.strftime('%Y-%m-%d')} | {scan.subtype} | {scan.predicted_class} | {scan.confidence:.0%} | {scan.confirmed_bin or 'N/A'} |\n"
    
    md += f"""

---

*{advice.disclaimer}*

*Report generated by ReCircle - Smart Recycling Assistant*
"""
    
    # Return as streaming response for download
    return StreamingResponse(
        io.BytesIO(md.encode()),
        media_type="text/markdown",
        headers={"Content-Disposition": f"attachment; filename=recircle-report-{metrics.timestamp.strftime('%Y%m%d')}.md"},
    )